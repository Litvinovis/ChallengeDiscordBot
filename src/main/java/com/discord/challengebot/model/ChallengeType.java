package com.discord.challengebot.model;

/**
 * Перечисление типов испытания.
 * Определяет, является ли испытание индивидуальным или групповым.
 */
public enum ChallengeType {
	/**
	 * Индивидуальное испытание, выполняемое одним участником
	 */
	INDIVIDUAL,
	/**
	 * Групповое испытание, в котором участвует несколько пользователей
	 */
	GROUP
}